local LKEY = "\128key\255" .. rep("k", 10)

local function sample(n)
	local s = {}
	for i = 0, n - 1 do
		s[i + 1] = (i % 3 == 0) and (128 + i * 7) % 256 or (i * 31 + 5) % 256
	end
	return #s == 0 and "" or string.char(unpack(s))
end

t.test("length boundaries with high bytes", function()
	for n, want in pairs(lens) do
		local m = sample(n)
		t.eq(#m, n)
		t.eq(Sha.hex(m), want.sha, "sha " .. n)
		t.eq(Sha.hmac(LKEY, m), want.hmac, "hmac " .. n)
		t.eq(Sha.toHex(Sha.hmacRaw(LKEY, m)), want.hmac, "hmacRaw " .. n)
	end
end)

t.test("keyed equals hmac", function()
	for _, key in ipairs({ "", "k", LKEY, rep("\170", 64), rep("\170", 131) }) do
		local f = Sha.keyed(key)
		for n = 0, 130, 13 do
			local m = sample(n)
			t.eq(f(m), Sha.hmac(key, m), "hex " .. n)
			t.eq(f(m, true), Sha.hmacRaw(key, m), "raw " .. n)
		end
		t.eq(f("again"), Sha.hmac(key, "again"), "reuse")
	end
end)

t.test("toHex and fromHex", function()
	local all = {}
	for i = 0, 255 do all[#all + 1] = string.char(i) end
	all = table.concat(all)
	t.eq(Sha.fromHex(Sha.toHex(all)), all)
	t.eq(Sha.toHex("\0\255a"), "00ff61")
	t.eq(Sha.fromHex("00ff61"), "\0\255a")
	t.eq(Sha.fromHex(""), "")
end)

t.test("fromHex rejects bad input", function()
	t.eq(Sha.fromHex("abc"), nil)
	t.eq(Sha.fromHex("0g"), nil)
	t.eq(Sha.fromHex("AB"), nil)
	t.eq(Sha.fromHex("a b"), nil)
	t.eq(Sha.fromHex("ab\n"), nil)
end)
